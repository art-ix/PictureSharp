namespace PictureSharp;

/// <summary>EXIF GPS altitude reference values (GPS tag 0x0005).</summary>
public enum ExifGpsAltitudeReference
{
    /// <summary>The altitude is above sea level.</summary>
    AboveSeaLevel = 0,
    /// <summary>The altitude is below sea level.</summary>
    BelowSeaLevel = 1,
}
